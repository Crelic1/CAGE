"""The egress proxy that keeps the docker host off the agent's networks.

A docker bridge gives the host an address on every network it creates, and the
host listens on ``0.0.0.0`` — so any container can dial its sshd, its inspector,
and the published ports of every other run. Sealing only the agent's own network
does not fix it either: the agent takes a target machine and uses *that* stack,
which sits on the range's compose networks where the host is the gateway again.

The shape that closes both legs::

    docker network create --subnet 10.90.1.0/24 --gateway 10.90.1.1 \\
        -o com.docker.network.bridge.inhibit_ipv4=true <net>

``inhibit_ipv4`` leaves the bridge address-less on the host side, so the host is
not on the network at all, while docker still hands every container
``default via 10.90.1.1``. This module's container claims that address and
becomes the only way out. Containers need no changes whatsoever: no NET_ADMIN,
no proxy environment variables (which would send ``http://web`` at the proxy and
break the alias resolution a range depends on), no routes, no image edits.

Lifecycle is per HOST, not per run: several runs share one proxy, so bringing it
up is idempotent and nothing here ever tears it down at the end of a run.

The policy itself lives in ``docker/netproxy/entrypoint.sh``.
"""

from __future__ import annotations

import contextlib
import fcntl
import ipaddress
import logging
import os
import re
import shutil
import subprocess
import tempfile
import time
from collections.abc import Iterator
from pathlib import Path

logger = logging.getLogger("cage.sandbox.netproxy")

# Bumped whenever the entrypoint's policy changes: ``ensure_image`` only builds
# when the tag is missing, and ``ensure_running`` leaves a running proxy alone,
# so a stale tag is how a fixed policy silently fails to take effect.
IMAGE = "cage/netproxy:v1.1"
CONTAINER = "cage-netproxy"
NETWORK = "cage-agent-net"
SUBNET = "10.90.1.0/24"
REDIR_PORT = 7892
HOST_OFF_BRIDGE_OPT = "com.docker.network.bridge.inhibit_ipv4"

# Where the image's build context lives, relative to the installed package.
BUILD_CONTEXT = Path(__file__).resolve().parents[2] / "docker" / "netproxy"

# Looked at in order when no path is configured. Without a mihomo binary the
# proxy still works — it just NATs straight out, which is enough for endpoints
# reachable directly and useless for ones behind an upstream proxy.
MIHOMO_CANDIDATES = (
    "mihomo",
    "clash-meta",
    "clash",
)

# Two settings in the generated config are load-bearing and must not be
# "improved" (see the entrypoint for the long version):
#   * no fake-ip — otherwise the proxy forwards a hostname upstream and
#     ``http://<host-ip>.nip.io`` becomes a working SSRF into the host.
#   * no sniffer — it rebuilds a hostname from SNI/Host, same hole.
_MIHOMO_CONF = """\
# generated by cage.sandbox.netproxy
redir-port: {redir_port}
allow-lan: true
bind-address: '*'
mode: rule
log-level: warning
sniffer:
  enable: false
{proxies}rules:
  - MATCH,{target}
"""

_UPSTREAM_BLOCK = """\
proxies:
  - name: upstream
    type: http
    server: {host}
    port: {port}
"""


class NetproxyError(RuntimeError):
    """Raised when the proxy cannot be brought into the required state."""


# One lock for the whole host, because there is one proxy for the whole host.
BRINGUP_LOCK_PATH = Path(tempfile.gettempdir()) / "cage-netproxy.bringup.lock"


@contextlib.contextmanager
def _bringup_lock(timeout: float = 900.0) -> Iterator[bool]:
    """Serialise bring-up across every run on this machine.

    Without it, "is it up? no — then start it" is two docker calls with a gap,
    and two runs starting together both pass the check. The one that gets there
    second finds a container that exists (the first one's, seconds old), force
    removes it as if it were a leftover, and starts its own. The first run has
    already returned success by then: it goes on to run trials against a proxy
    that was replaced underneath it, whose allow-list never received its model
    endpoints, and every trial dies on a connect timeout with nothing pointing
    at the cause. The window is small but it is exactly the window a deploy
    opens — ``docker rm -f cage-netproxy`` and then several runs starting.

    Held across the whole sequence, not just the create: the allow-list merge is
    a read-modify-write on a file inside the container and races the same way.

    Yields whether the lock was actually held. Failing to take it is never
    allowed to fail a run — a machine where the lock file is not writable is
    still better served by the old racy behaviour than by refusing to start.
    """
    deadline = time.monotonic() + timeout
    handle = None
    try:
        handle = os.open(BRINGUP_LOCK_PATH, os.O_CREAT | os.O_RDWR, 0o666)
    except OSError as exc:
        logger.warning(
            "netproxy: cannot open %s (%s) — bringing the proxy up without a "
            "lock; concurrent runs may collide", BRINGUP_LOCK_PATH, exc,
        )
        yield False
        return
    try:
        while True:
            try:
                fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except OSError:
                if time.monotonic() >= deadline:
                    logger.warning(
                        "netproxy: waited %.0fs for %s and gave up — proceeding "
                        "unserialised", timeout, BRINGUP_LOCK_PATH,
                    )
                    yield False
                    return
                time.sleep(0.2)
        try:
            yield True
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)
    finally:
        os.close(handle)


def _docker(*args: str, check: bool = False, timeout: float = 120.0) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["docker", *args], capture_output=True, text=True,
        stdin=subprocess.DEVNULL, timeout=timeout, check=check,
    )


def _exists(kind: str, name: str) -> bool:
    return _docker(kind, "inspect", name).returncode == 0


def _running(container: str) -> bool:
    result = _docker("inspect", "-f", "{{.State.Running}}", container)
    return result.returncode == 0 and result.stdout.strip() == "true"


def running_image(container: str = CONTAINER) -> str:
    """The image tag the running proxy was started from (``""`` if unknown)."""
    result = _docker("inspect", "-f", "{{.Config.Image}}", container)
    return result.stdout.strip() if result.returncode == 0 else ""


def stale(container: str = CONTAINER, image: str = IMAGE) -> bool:
    """Whether the running proxy predates the policy this version ships.

    Worth its own function because the failure it prevents is silent: the
    container is shared per host and never restarted at the end of a run, so a
    proxy started weeks ago keeps serving its old rules while the code here
    believes the current ones are in force.
    """
    current = running_image(container)
    return bool(current) and current != image


def host_min_mtu(floor: int = 1280) -> int:
    """Smallest MTU among the host's up interfaces, for the networks we create.

    Containers otherwise get docker's default 1500 and have no way to learn
    better: when the path out leaves through something smaller — a tailscale or
    WireGuard interface is 1280 — the oversized packets are dropped, and the
    ICMP "fragmentation needed" that would fix it does not survive the NAT back
    to the container. The failure is nastily specific: the TCP handshake
    succeeds (small packets) and TLS then hangs forever (large ones), which
    reads like the endpoint being down rather than a path problem.

    The host itself never hits this — its own sockets know the route's MTU. So
    matching the host's smallest interface is what puts containers on equal
    footing. Never goes below ``floor`` (IPv6's minimum) or above 1500.
    """
    try:
        result = subprocess.run(
            ["ip", "-o", "link", "show", "up"],
            capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=30.0,
        )
    except Exception:
        return 1500
    mtus: list[int] = []
    for line in result.stdout.splitlines():
        if " lo:" in line or "LOOPBACK" in line:
            continue
        match = re.search(r"\bmtu (\d+)", line)
        if match:
            value = int(match.group(1))
            # Ignore oddities like a 65536 loopback-ish or a stale 68-byte tunnel.
            if 576 <= value <= 65535:
                mtus.append(value)
    if not mtus:
        return 1500
    return max(floor, min(1500, min(mtus)))


def host_holds_address_on(network: str) -> bool | None:
    """Whether the docker host has an address on ``network``'s bridge.

    This — not the declared gateway — is the question that matters: a contained
    network declares a gateway on purpose (containers need a default route to
    the proxy) while keeping the host off the bridge. Returns ``None`` when the
    answer cannot be determined.
    """
    # Newline-separated: a network with no explicit bridge name renders as the
    # literal ``<no value>``, which splitting on whitespace turns into two
    # tokens and yields the bogus interface name ``<no``.
    result = _docker(
        "network", "inspect", network,
        "--format", "{{.Id}}\n{{index .Options \"com.docker.network.bridge.name\"}}",
    )
    if result.returncode != 0 or not result.stdout.strip():
        return None
    lines = result.stdout.splitlines()
    net_id = lines[0].strip()
    named = lines[1].strip() if len(lines) > 1 else ""
    bridge = named if named and named != "<no value>" else f"br-{net_id[:12]}"
    probe = subprocess.run(
        ["ip", "-4", "-o", "addr", "show", "dev", bridge],
        capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=30.0,
    )
    if probe.returncode != 0:
        return None
    return bool(probe.stdout.strip())


def host_resolvers() -> list[str]:
    """The nameservers the docker host actually reaches the DNS system through.

    The proxy's caching resolver needs a forwarder, and it cannot inherit the
    container's own ``/etc/resolv.conf``: docker writes ``127.0.0.11`` there and
    the embedded resolver behind that address is not always running in a
    container that was created on the default bridge — which yields a resolver
    that accepts queries and can never answer one. Loopback entries are skipped
    for the same reason (``127.0.0.53`` is systemd-resolved on the host, not
    reachable from a container), falling back to the real servers systemd keeps
    in its own file — the same chain docker follows to fill in ``ExtServers``.
    """
    candidates = (Path("/etc/resolv.conf"), Path("/run/systemd/resolve/resolv.conf"))
    servers: list[str] = []
    for path in candidates:
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for line in text.splitlines():
            parts = line.split()
            if len(parts) < 2 or parts[0] != "nameserver":
                continue
            try:
                address = ipaddress.ip_address(parts[1])
            except ValueError:
                continue
            if address.is_loopback or address.version != 4:
                continue
            if parts[1] not in servers:
                servers.append(parts[1])
        if servers:
            break
    return servers


def find_mihomo(configured: str = "") -> str:
    """Locate a mihomo/clash binary to hand the proxy, or ``""``."""
    if configured:
        path = Path(configured).expanduser()
        if not path.is_file():
            raise NetproxyError(f"netproxy_mihomo path does not exist: {path}")
        return str(path)
    for candidate in MIHOMO_CANDIDATES:
        found = shutil.which(candidate)
        if found:
            return found
    return ""


def ensure_image(image: str = IMAGE) -> None:
    if _exists("image", image):
        return
    if not BUILD_CONTEXT.is_dir():
        raise NetproxyError(f"image {image} is missing and no build context at {BUILD_CONTEXT}")
    logger.info("building %s from %s", image, BUILD_CONTEXT)
    result = _docker("build", "-t", image, str(BUILD_CONTEXT), timeout=900.0)
    if result.returncode != 0:
        raise NetproxyError(f"could not build {image}: {result.stderr.strip()[:400]}")


def ensure_network(network: str = NETWORK, subnet: str = SUBNET) -> None:
    """Create the agent network with the host kept off it (idempotent)."""
    if _exists("network", network):
        if host_holds_address_on(network):
            raise NetproxyError(
                f"network {network} exists but the host holds an address on its "
                f"bridge — it was not created with {HOST_OFF_BRIDGE_OPT}, so the "
                f"host is reachable from it. Remove it (docker network rm "
                f"{network}) and let cage recreate it."
            )
        return
    gateway = str(next(ipaddress.ip_network(subnet).hosts()))
    mtu = host_min_mtu()
    result = _docker(
        "network", "create", "--subnet", subnet, "--gateway", gateway,
        "-o", f"{HOST_OFF_BRIDGE_OPT}=true",
        "-o", f"com.docker.network.driver.mtu={mtu}", network,
    )
    if result.returncode != 0:
        hint = ""
        if "overlaps" in result.stderr:
            hint = " — another network already uses that subnet; set runtime.netproxy_subnet"
        elif "inhibit_ipv4" in result.stderr:
            hint = " — this needs Docker 26+"
        raise NetproxyError(f"could not create {network}: {result.stderr.strip()[:300]}{hint}")
    logger.info("created contained network %s (gateway %s, mtu %d, host not on it)",
                network, gateway, mtu)


def ensure_running(
    *,
    upstream: str = "",
    mihomo: str = "",
    allow_nets: list[str] | None = None,
    dns_upstream: str = "",
    image: str = IMAGE,
    container: str = CONTAINER,
    network: str = NETWORK,
    subnet: str = SUBNET,
    redir_port: int = REDIR_PORT,
) -> None:
    """Bring the proxy up if it is not already serving. Idempotent.

    Shared by every run on the machine, so an already-running proxy is left
    alone — restarting it would cut the network out from under concurrent runs.

    ``dns_upstream`` overrides what the in-proxy caching resolver forwards to
    (space-separated servers); empty means the servers the docker host uses.
    """
    # Everything below is one check-then-act sequence over host-wide state:
    # the image, the network, the container, and the files inside it. One
    # lock over the lot, so a second run either waits or finds it done.
    with _bringup_lock():
        ensure_image(image)
        ensure_network(network, subnet)

        if _running(container):
            # Already serving another run. Do not restart it — that would cut the
            # network out from under runs in flight. Just make sure it is on this
            # network and that this run's model endpoints are permitted.
            _docker("network", "connect", network, container)
            merge_allow_nets(allow_nets or [], container=container)
            _apply_dns_upstream(dns_upstream, container=container)
            if stale(container, image):
                logger.warning(
                    "%s is running from %s, not %s — it is serving the older "
                    "network policy and this version's changes (DNS caching, "
                    "conntrack warnings, fail-closed egress) are NOT in effect. "
                    "Restart it between runs with: docker rm -f %s",
                    container, running_image(container), image, container,
                )
            return

        if _exists("container", container):
            _docker("rm", "-f", container)

        allow = " ".join(sorted(set(allow_nets or [])))
        result = _docker(
            "run", "-d", "--name", container, "--restart", "unless-stopped",
            "--network", "bridge", "--cap-add", "NET_ADMIN", "--cap-add", "NET_RAW",
            "--sysctl", "net.ipv4.ip_forward=1",
            "-e", f"ALLOW_NETS={allow}", "-e", f"REDIR_PORT={redir_port}",
            # Seeds first boot only; the file written below is what the entrypoint
            # actually reads, so a later run can change it without a restart.
            "-e", f"DNS_UPSTREAM={dns_upstream or ' '.join(host_resolvers())}",
            image,
        )
        if result.returncode != 0:
            raise NetproxyError(f"could not start {container}: {result.stderr.strip()[:300]}")
        connect = _docker("network", "connect", network, container)
        if connect.returncode != 0:
            raise NetproxyError(
                f"{container} could not join {network}: {connect.stderr.strip()[:200]}")

        merge_allow_nets(allow_nets or [], container=container)
        _apply_dns_upstream(dns_upstream, container=container)

        binary = find_mihomo(mihomo)
        if binary:
            _docker("cp", binary, f"{container}:/usr/local/bin/mihomo")
            if upstream:
                host, _, port = upstream.rpartition(":")
                host = host.split("//")[-1]
                if not host or not port.isdigit():
                    raise NetproxyError(f"upstream proxy must be host:port (got {upstream!r})")
                proxies = _UPSTREAM_BLOCK.format(host=host, port=port)
                target = "upstream"
            else:
                proxies, target = "", "DIRECT"
            conf = _MIHOMO_CONF.format(redir_port=redir_port, proxies=proxies, target=target)
            subprocess.run(
                ["docker", "exec", "-i", container, "sh", "-c",
                 "mkdir -p /etc/mihomo && cat > /etc/mihomo/config.yaml"],
                input=conf, text=True, capture_output=True, timeout=60.0,
            )
        elif upstream:
            raise NetproxyError(
                f"an upstream proxy ({upstream}) was configured but no mihomo binary "
                f"was found — set runtime.netproxy_mihomo to its path, or drop the "
                f"upstream to egress directly"
            )
    logger.info(
        "netproxy %s serving %s (upstream=%s allow=%s)",
        container, network, upstream or "direct", allow or "none",
    )


ALLOW_NETS_PATH = "/etc/cage-netproxy/allow_nets"
DNS_UPSTREAM_PATH = "/etc/cage-netproxy/dns_upstream"


def merge_allow_nets(cidrs: list[str], *, container: str = CONTAINER) -> list[str]:
    """Add ``cidrs`` to the proxy's allow-list without restarting it.

    The list is a file the entrypoint re-reads every cycle rather than a startup
    env var, because one proxy serves every run on the machine: a run starting
    now must be able to permit its own model endpoints without disturbing runs
    already in flight. Merging (never replacing) is what keeps those runs' own
    endpoints permitted.
    """
    if not cidrs:
        return []
    existing = subprocess.run(
        ["docker", "exec", container, "sh", "-c", f"cat {ALLOW_NETS_PATH} 2>/dev/null || true"],
        capture_output=True, text=True, timeout=60.0,
    ).stdout.split()
    merged = sorted(set(existing) | set(cidrs))
    if merged == sorted(set(existing)):
        return merged
    subprocess.run(
        ["docker", "exec", "-i", container, "sh", "-c",
         f"mkdir -p $(dirname {ALLOW_NETS_PATH}) && cat > {ALLOW_NETS_PATH}"],
        input="\n".join(merged) + "\n", text=True, capture_output=True, timeout=60.0,
    )
    logger.info("netproxy allow-list now permits %s", ", ".join(merged))
    return merged


def set_dns_upstream(
    servers: str, *, container: str = CONTAINER, only_if_unset: bool = False,
) -> None:
    """Point the proxy's caching resolver at ``servers`` without restarting it.

    A file the entrypoint re-reads, not a startup env var, for the reason the
    allow-list learned the hard way: one proxy serves every run on the machine,
    and a run that starts second would otherwise silently keep the first run's
    settings — a configured knob that quietly does nothing.

    ``only_if_unset`` is for the derived default (the host's own nameservers,
    which every run computes identically): it must not overwrite a value an
    earlier run set on purpose through ``runtime.netproxy_dns_upstream``.
    """
    if not servers.strip():
        return
    if only_if_unset:
        probe = subprocess.run(
            ["docker", "exec", container, "sh", "-c",
             f"test -s {DNS_UPSTREAM_PATH} && echo set || true"],
            capture_output=True, text=True, timeout=60.0,
        )
        if "set" in probe.stdout:
            return
    subprocess.run(
        ["docker", "exec", "-i", container, "sh", "-c",
         f"mkdir -p $(dirname {DNS_UPSTREAM_PATH}) && cat > {DNS_UPSTREAM_PATH}"],
        input="\n".join(servers.split()) + "\n", text=True,
        capture_output=True, timeout=60.0,
    )
    logger.info("netproxy resolver now forwards to %s", servers)


def _apply_dns_upstream(configured: str, *, container: str = CONTAINER) -> None:
    """Write whichever resolver list this run is entitled to set.

    An explicit ``runtime.netproxy_dns_upstream`` wins and overwrites. The
    derived host default does not: every run computes the same one, so letting
    it write would silently undo a deliberate choice made by an earlier run.
    """
    if configured.strip():
        set_dns_upstream(configured, container=container)
    else:
        set_dns_upstream(
            " ".join(host_resolvers()), container=container, only_if_unset=True,
        )


def attach(network: str, *, container: str = CONTAINER) -> bool:
    """Put the proxy on ``network`` so it can be that network's gateway."""
    result = _docker("network", "connect", network, container)
    if result.returncode == 0 or "already exists" in (result.stderr or ""):
        return True
    logger.warning("netproxy could not join %s: %s", network, result.stderr.strip()[:200])
    return False


def detach(network: str, *, container: str = CONTAINER) -> bool:
    """Take the proxy off ``network`` so the network can be removed.

    The proxy is not part of any compose project, so nothing else removes it and
    docker refuses to delete a network that still has an endpoint.
    """
    result = _docker("network", "disconnect", "-f", network, container)
    if result.returncode == 0:
        logger.info("netproxy detached from %s", network)
        return True
    logger.debug("netproxy detach from %s: %s", network, (result.stderr or "").strip()[:160])
    return False


def is_serving(*, container: str = CONTAINER, network: str = NETWORK) -> bool:
    return _running(container) and _exists("network", network)
