valid_image_tar() {
  python3 - "$1" <<'PY'
import json
import sys
import tarfile

try:
    with tarfile.open(sys.argv[1]) as archive:
        names = set(archive.getnames())
        manifest_name = "manifest.json" if "manifest.json" in names else "./manifest.json"
        manifest = json.load(archive.extractfile(manifest_name))
        layers = manifest[0]["Layers"]
        if not layers or any(layer not in names and "./" + layer not in names for layer in layers):
            raise ValueError("manifest layer missing")
except Exception as exc:
    print(f"invalid image tar: {exc}", file=sys.stderr)
    raise SystemExit(1)
PY
}

download_mode() {
  local ident="$1" mode="$2"
  local image="n132/arvo:${ident}-${mode}"
  local target="$CACHE_DIR/n132_arvo/${ident}-${mode}.tar"
  local part="${target}.part.${BASHPID}"
  local attempt quarantine

  if [[ -f "$target" ]]; then
    if valid_image_tar "$target" >/dev/null 2>&1; then
      log "cache-hit arvo:$ident $mode"
      return 0
    fi
    quarantine="${target}.invalid.$(date +%Y%m%dT%H%M%S).${BASHPID}"
    mv "$target" "$quarantine"
    log "quarantine arvo:$ident $mode -> $quarantine"
  fi

  for ((attempt = 1; attempt <= RETRIES; attempt++)); do
    rm -f "$part"
    log "pull arvo:$ident $mode attempt=$attempt/$RETRIES"
    if timeout "$PULL_TIMEOUT" "$CRANE" pull "$image" "$part" && valid_image_tar "$part"; then
      mv "$part" "$target"
      log "pull-ok arvo:$ident $mode"
      return 0
    fi
    rm -f "$part"
    log "pull-failed arvo:$ident $mode attempt=$attempt/$RETRIES"
  done
  return 1
}

download_id() {
  local ident="$1" status=0
  download_mode "$ident" vul || status=1
  download_mode "$ident" fix || status=1
  return "$status"
}

extract_batch() {
  local ids_csv="$1"
  log "extract-start ids=$ids_csv"
  if ! python3 "$BINARY_EXTRACTOR" \
      --image-cache "$CACHE_DIR" \
      --task-ids "$ids_csv" \
      --out "$DEST_ROOT" \
      --allow-partial \
      --jobs "$EXTRACT_JOBS"; then
    log "extract-binaries-failed ids=$ids_csv"
  fi
  if ! python3 "$POC_EXTRACTOR" \
      --vulcache "$CACHE_DIR/n132_arvo" \
      --out "$DEST_ROOT/arvo" \
      --ids "$ids_csv" \
      --workers "$EXTRACT_JOBS"; then
    log "extract-poc-failed ids=$ids_csv"
  fi
  if ! python3 "$SOURCE_EXTRACTOR" \
      --image-cache "$CACHE_DIR" \
      --out "$DEST_ROOT" \
      --ids "$ids_csv" \
      --workers "$EXTRACT_JOBS"; then
    log "extract-source-failed ids=$ids_csv"
  fi
  log "extract-end ids=$ids_csv"
}

cleanup_children() {
  local pid
  local -a child_pids=()
  mapfile -t child_pids < <(jobs -pr)
  for pid in "${child_pids[@]}"; do
    kill "$pid" 2>/dev/null || true
  done
  for pid in "${child_pids[@]}"; do
    wait "$pid" 2>/dev/null || true
  done
}
