#!/usr/bin/env bash
# Portable collector for the 2,244 non-CyberGym ARVO environments that were
# absent from CAGE's 2026-07-22 inventory. The inventory and extraction helpers
# are embedded below, so this file can be copied and run on another Linux host.
set -Eeuo pipefail

readonly PULL_CONCURRENCY=16
readonly EXTRACT_JOBS=4
readonly ARVO_IDS_SHA256="b54089e3eda6571eb563be9e8217e330315bdce3d993a6366bd05501b4e48c16"
readonly BINARY_EXTRACTOR_SHA256="38bfc20f8b8de935b0923e75d27f76485c0755ab2000f2d8a9fae18edd0c1976"
readonly POC_EXTRACTOR_SHA256="a5c84465b5a13bac673cae0930f4f9aed5dcf204b0ea07a31ec52ab117906e41"
readonly SOURCE_EXTRACTOR_SHA256="d9cb50550d72fddf1c9089d1a2046844ba4083fd3daff0a9350f30fbda8a3046"

SCRIPT_PATH="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"
DEST_ROOT="${ARVO_DEST_ROOT:-$PWD/arvo-missing}"
CACHE_DIR=""
CRANE="${CRANE:-crane}"
PROXY=""
PULL_TIMEOUT=3600
RETRIES=3
LIMIT=0
KEEP_IMAGES=0
DRY_RUN=0
LOG=""

usage() {
  cat <<'EOF'
Usage: download_missing_arvo_environments.sh [options]

Download the embedded 2,244-ID ARVO inventory in batches with at most
16 concurrent crane pulls. After every batch, extract these local artifacts:

  <out>/arvo/<id>/vul/{arvo,out/,libs/}
  <out>/arvo/<id>/fix/{arvo,out/,libs/}
  <out>/arvo/<id>/poc
  <out>/arvo/<id>/repo-vul.tar.gz   (src-vul/<repo>/..., without .git)
  <out>/arvo/<id>/commits.json      (vul/fix commits for the archived repos)

Options:
  --out DIR             Destination root (default: ./arvo-missing)
  --cache-dir DIR       Image-tar cache (default: <out>/.image-cache)
  --crane PATH          crane executable (default: crane from PATH)
  --proxy URL           Set HTTP(S)_PROXY for crane
  --pull-timeout SEC    Timeout for one image pull (default: 3600)
  --retries N           Attempts per image (default: 3)
  --limit N             Process only the first N embedded IDs (smoke tests)
  --keep-images         Retain image tars after successful extraction
  --dry-run             Print pending IDs without downloading
  --print-ids           Print the embedded IDs and exit
  -h, --help            Show this help

No repo-fix.tar.gz or patch.diff is generated. The default removes a batch's
image tars only after all listed outputs pass the local completeness check.
Re-running is safe and resumes from the filesystem state.
EOF
}

embedded_ids() {
  sed -n '/^# BEGIN ARVO_IDS$/,/^# END ARVO_IDS$/ {
    /^# BEGIN ARVO_IDS$/d
    /^# END ARVO_IDS$/d
    p
  }' "$SCRIPT_PATH"
}

die() {
  printf 'error: %s\n' "$*" >&2
  exit 2
}

is_uint() {
  [[ "$1" =~ ^[0-9]+$ ]]
}

while (($#)); do
  case "$1" in
    --out) (($# >= 2)) || die "--out needs a value"; DEST_ROOT="$2"; shift 2 ;;
    --cache-dir) (($# >= 2)) || die "--cache-dir needs a value"; CACHE_DIR="$2"; shift 2 ;;
    --crane) (($# >= 2)) || die "--crane needs a value"; CRANE="$2"; shift 2 ;;
    --proxy) (($# >= 2)) || die "--proxy needs a value"; PROXY="$2"; shift 2 ;;
    --pull-timeout) (($# >= 2)) || die "--pull-timeout needs a value"; PULL_TIMEOUT="$2"; shift 2 ;;
    --retries) (($# >= 2)) || die "--retries needs a value"; RETRIES="$2"; shift 2 ;;
    --limit) (($# >= 2)) || die "--limit needs a value"; LIMIT="$2"; shift 2 ;;
    --keep-images) KEEP_IMAGES=1; shift ;;
    --dry-run) DRY_RUN=1; shift ;;
    --print-ids) embedded_ids; exit 0 ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown option: $1" ;;
  esac
done

is_uint "$PULL_TIMEOUT" && ((PULL_TIMEOUT > 0)) || die "--pull-timeout must be positive"
is_uint "$RETRIES" && ((RETRIES > 0)) || die "--retries must be positive"
is_uint "$LIMIT" || die "--limit must be a non-negative integer"

if [[ -z "$CACHE_DIR" ]]; then
  CACHE_DIR="$DEST_ROOT/.image-cache"
fi

mapfile -t INVENTORY_IDS < <(embedded_ids)
ALL_IDS=("${INVENTORY_IDS[@]}")
if ((LIMIT > 0 && LIMIT < ${#ALL_IDS[@]})); then
  ALL_IDS=("${ALL_IDS[@]:0:LIMIT}")
fi

complete_environment() {
  local ident="$1" task="$DEST_ROOT/arvo/$1"
  local vul_out fix_out
  [[ -f "$task/.collector-ready" ]] || return 1
  artifacts_present "$ident"
}

artifacts_present() {
  local ident="$1" task="$DEST_ROOT/arvo/$1"
  local vul_out fix_out
  [[ -s "$task/vul/arvo" && -s "$task/fix/arvo" && -f "$task/poc" ]] || return 1
  [[ -s "$task/repo-vul.tar.gz" && -s "$task/commits.json" ]] || return 1
  [[ -d "$task/vul/out" && -d "$task/fix/out" ]] || return 1
  [[ -d "$task/vul/libs" && -d "$task/fix/libs" ]] || return 1
  vul_out="$(find "$task/vul/out" -type f -print -quit 2>/dev/null || true)"
  fix_out="$(find "$task/fix/out" -type f -print -quit 2>/dev/null || true)"
  [[ -n "$vul_out" && -n "$fix_out" ]]
}

PENDING_IDS=()
for ident in "${ALL_IDS[@]}"; do
  if ! complete_environment "$ident"; then
    PENDING_IDS+=("$ident")
  fi
done

if ((DRY_RUN)); then
  printf 'inventory=%d pending=%d concurrency=%d out=%s cache=%s\n' \
    "${#ALL_IDS[@]}" "${#PENDING_IDS[@]}" "$PULL_CONCURRENCY" "$DEST_ROOT" "$CACHE_DIR"
  printf '%s\n' "${PENDING_IDS[@]}"
  exit 0
fi

for command_name in python3 base64 gzip sha256sum timeout find; do
  command -v "$command_name" >/dev/null || die "required command not found: $command_name"
done
actual_ids_sha256="$(printf '%s\n' "${INVENTORY_IDS[@]}" | sha256sum | cut -d' ' -f1)"
[[ "$actual_ids_sha256" == "$ARVO_IDS_SHA256" ]] || die "embedded ARVO inventory checksum mismatch"
if [[ "$CRANE" == */* ]]; then
  [[ -x "$CRANE" ]] || die "crane is not executable: $CRANE"
else
  CRANE="$(command -v "$CRANE")" || die "crane not found: $CRANE"
fi

mkdir -p "$CACHE_DIR/n132_arvo" "$DEST_ROOT/arvo" "$DEST_ROOT/.collector/helpers"
LOG="$DEST_ROOT/.collector/download.log"
FAILED_FILE="$DEST_ROOT/.collector/incomplete_ids.txt"

if [[ -n "$PROXY" ]]; then
  export HTTP_PROXY="$PROXY" HTTPS_PROXY="$PROXY" http_proxy="$PROXY" https_proxy="$PROXY"
fi

log() {
  local line
  printf -v line '[%(%Y-%m-%dT%H:%M:%S%z)T] %s' -1 "$*"
  printf '%s\n' "$line"
  printf '%s\n' "$line" >>"$LOG"
}

decode_helper() {
  local target="$1" expected="$2" tmp="$1.part.$$" actual
  base64 --decode | gzip -dc >"$tmp"
  actual="$(sha256sum "$tmp" | cut -d' ' -f1)"
  if [[ "$actual" != "$expected" ]]; then
    rm -f "$tmp"
    die "embedded helper checksum mismatch for $target"
  fi
  chmod 755 "$tmp"
  mv -f "$tmp" "$target"
}

